// Configurazione MathJax 3 per pymdownx.arithmatex (generic).
// Metodo ufficiale di MkDocs Material: nessun uso di polyfill.io.
window.MathJax = {
  tex: {
    inlineMath: [["\\(", "\\)"]],
    displayMath: [["\\[", "\\]"]],
    processEscapes: true,
    processEnvironments: true
  },
  options: {
    ignoreHtmlClass: ".*|",
    processHtmlClass: "arithmatex"
  }
};

// Ri-renderizza le formule quando Material naviga in modalità "instant".
document$.subscribe(() => {
  MathJax.startup.output.clearCache();
  MathJax.typesetClear();
  MathJax.texReset();
  MathJax.typesetPromise();
});
